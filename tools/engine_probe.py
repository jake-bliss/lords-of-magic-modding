def install(hotkey_source: str, probe: str = "ladder") -> str:
    """Insert a probe before `hotkey.gs`'s final `end`, which the file warns not to pass."""
    if probe not in PROBES:
        raise ValueError(f"unknown probe {probe!r}; choose from {sorted(PROBES)}")
    marker = "\nend ; DO NOT ADD AFTER 'END'!"
    if hotkey_source.count(marker) != 1:
        raise ValueError(
            f"expected exactly one {marker.strip()!r} marker, found "
            f"{hotkey_source.count(marker)}"
        )
    return hotkey_source.replace(marker, "\n" + PROBES[probe]() + marker)


def disable_intro(start_source: str) -> str:
    """Turn off the two startup movies, which cost minutes of every attended run."""
    guard = '\ntrue\n\t{\n\t75 75"smk/imptitle.smk"MODAL playvideo '
    if start_source.count(guard) != 1:
        raise ValueError("START.GS intro guard not found in its expected form")
    return start_source.replace(guard, guard.replace("\ntrue\n", "\nfalse\n", 1), 1)


