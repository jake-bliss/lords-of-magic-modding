"""Generate the GameScript hotkey body for the sprite placement / palette probe.

The probe is a *diagnostic ladder*, not a single measurement. The 2026-09-16 run failed
because a custom terrain sprite type built from an injected archive member registered an id
but rendered nothing, and there was no control that could say why. Four sprite types are now
placed side by side in one capture:

    zt0  shipped type, shipped art      terrainsprites /orchard get
    zt1  custom type,  shipped art      ["imp/tree4e.imp"] cvx addterrainspritetype
    zt2  custom type,  injected copy    ["imp/zzctl.imp"]  cvx addterrainspritetype
    zt3  custom type,  authored palette ["imp/zzpal.imp"]  cvx addterrainspritetype

Whichever rung the ladder breaks on names the cause: the operator, the injection, or the
palette edit. `zzctl.imp` is byte-identical to `imp\\tree4e.imp`, so zt1 versus zt2 isolates
"the engine cannot read an added member" from "our edit broke the file".

Two hazards the previous run walked into, both fixed here:

- `anythingat?` does **not** see terrain sprites, so a cell can read empty and still hold a
  village. `terrainspriteat` then handed back somebody else's outpost and it was destroyed, so
  cleanup never matches on location alone. It does not match on **type** alone either: rung 0
  reuses the *shipped* orchard type, and destroying by that type would delete every orchard the
  map generator placed. Cleanup requires type **and** cell; only the freshly registered ids get
  a second type-only sweep, since nothing else on the map can be carrying them.
- The hotkey auto-repeats while the key is held. A `zdone` flag in `userdict` makes the body
  fire exactly once per launch.

**Locations are packed, not pairs.** `anythinglocation` and `getterrainspritelocation` each
return ONE value, `y * map_width + x`, and `findemptylocation` takes `(location, unittype)` --
two operands. The shipped corpus is the authority here: `anythinglocation xy_to_x_y` appears 31
times, and `/temple_loc temple_id getterrainspritelocation def` stores a single scalar. The
recovered arity table undercounts and must not be used to design an operand order. Reading a
packed location as a pair underflows the stack and kills the body silently: the 2026-09-16 run
logged an empty x beside `9152`, which at map width 128 is cell (64,71).
"""

from __future__ import annotations

# (label, GameScript expression yielding a terrain sprite type id)
SPRITE_TYPES: list[tuple[str, str]] = [
    ("shipped_type_shipped_art", "terrainsprites /orchard get"),
    ("custom_type_shipped_art", '["imp/tree4e.imp"]cvx addterrainspritetype'),
    ("custom_type_injected_copy", '["imp/zzctl.imp"]cvx addterrainspritetype'),
    ("custom_type_authored_palette", '["imp/zzpal.imp"]cvx addterrainspritetype'),
]

# Seed offsets from the army cell, one per sprite type. `findemptylocation` walks outward from each
# seed, so the seeds have to be far enough apart that two rungs cannot converge on one cell -- two
# sprites in the same cell makes the ladder unreadable. A cell is about 34 screen pixels of x, and
# the donor frame is 72 wide, so 2 cells is the minimum separation and 4 is comfortable. Laying them
# along one axis also gives four collinear points for the cell-to-screen fit.
SEED_OFFSETS: list[tuple[int, int]] = [(2, 0), (4, 0), (-2, 0), (-4, 0)]

HOTKEY = "z"


def is_freshly_registered(index: int) -> bool:
    """True when the type id is minted by this keypress rather than reused from the game.

    Only a freshly registered id is safe to clean up by type alone: no sprite the probe did not
    place can be carrying it. Rung 0 deliberately reuses a shipped type, and is therefore the one
    rung that must always be matched by cell as well.
    """
    return "addterrainspritetype" in SPRITE_TYPES[index][1]


def _log(text: str) -> str:
    """One `zprobe.log` line. `build_statement` interpolates the non-string tokens."""
    return f"zlog{{{text}}}build_statement writestring zlog carriage_return"


def probe_body() -> str:
    lines: list[str] = []
    emit = lines.append

    emit("; ---- BEGIN SPRITE PLACEMENT PROBE (generated by tools/engine_probe.py) ----")
    emit(f'ASCII_VAL"{HOTKEY}"0 get')
    emit("{")
    emit("userdict /zdone known not")
    emit("\t{")
    emit("\tuserdict begin")
    emit("\t/zdone true def")
    emit('\t"zprobe.log""abw"file /zlog exch def')

    # Settle the map first. The previous plate was captured before any rendermap, so the whole
    # terrain sprite layer appeared in the difference and swamped the subject.
    emit("\trendermap refreshdirty")
    emit('\t"zl0.bmp"screencapture')

    # `anythinglocation` returns ONE PACKED LOCATION, not an x/y pair. The shipped corpus settles it
    # -- `anythinglocation xy_to_x_y` appears 31 times, and you do not decompose an already
    # decomposed pair. The 2026-09-16 run proves it too: its log line printed an empty x and
    # y=9152, which at map width 128 is cell (64,71). Reading it as a pair underflows the stack and
    # kills the body before the first placement.
    emit("\t/zaloc -1 def /zseen false def")
    emit(
        "\tcurrentplayer{zseen not{anythinglocation /zaloc exch def /zseen true def}"
        "{pop}ifelse}enumplayerarmies"
    )
    emit("\tzseen")
    emit("\t\t{")
    emit("\t\tzaloc xy_to_x_y /zay0 exch def /zax0 exch def")
    emit("\t\t" + _log('"army loc "zaloc" cell "zax0" "zay0'))

    for index, ((label, expression), (dx, dy)) in enumerate(
        zip(SPRITE_TYPES, SEED_OFFSETS), start=0
    ):
        emit(f"\t\t{expression} /zt{index} exch def")
        # `findemptylocation` takes (location, unittype) -- two operands, not three. Shipped form:
        # `unit_loc UNITTYPELAND findemptylocation /unit_loc exch def`. `x_y_to_xy` packs the pair.
        emit(
            f"\t\tzax0 {dx} add zay0 {dy} add x_y_to_xy UNITTYPELAND findemptylocation "
            f"/zl{index} exch def"
        )
        emit(f"\t\tzl{index} xy_to_x_y /zy{index} exch def /zx{index} exch def")
        emit(f"\t\tzx{index} zy{index} 0 map2screen /zm3 exch def /zm2 exch def /zm1 exch def")
        emit(
            "\t\t"
            + _log(
                f'"type {index} {label} id "zt{index}" loc "zl{index}'
                f'" cell "zx{index}" "zy{index}" m2s "zm1" "zm2" "zm3'
            )
        )
        # Place before resolving the next rung, so `findemptylocation` has a chance to route around
        # a cell this probe just filled.
        emit(f"\t\tzx{index} zy{index} zt{index} addterrainsprite")

    emit("\t\trendermap refreshdirty")
    emit('\t\t"zl1.bmp"screencapture')

    # Cleanup must match the type *and* the cell the probe placed it on. Matching on location alone
    # destroyed a village; matching on type alone is worse, because rung 0 reuses the **shipped**
    # orchard type and would delete every orchard the map generator placed.
    # `getterrainspritelocation` also returns ONE packed location -- shipped uses are
    # `/temple_loc temple_id getterrainspritelocation def` and `... getterrainspritelocation 4 mod`.
    # Compare it against the packed cell the probe placed on, not against a decomposed pair.
    for index in range(len(SPRITE_TYPES)):
        emit(
            f"\t\t{{dup getterrainspritetype zt{index} eq"
            f"{{dup getterrainspritelocation zl{index} eq"
            "{destroyterrainsprite}{pop}ifelse}"
            "{pop}ifelse}enumterrainsprites"
        )
    # A second, type-only pass for the three freshly registered types. Their ids were minted by this
    # keypress, so nothing else on the map can carry them, and it catches anything the first pass
    # skipped -- destroying during an enumeration may advance past an entry.
    for index in range(len(SPRITE_TYPES)):
        if not is_freshly_registered(index):
            continue
        emit(
            f"\t\t{{dup getterrainspritetype zt{index} eq"
            "{destroyterrainsprite}{pop}ifelse}enumterrainsprites"
        )
    emit("\t\trendermap refreshdirty")
    emit('\t\t"zl2.bmp"screencapture')
    emit("\t\t" + _log('"cleanup done"'))
    emit("\t\t}")
    # No army means no anchor cell, so say so in the log rather than placing at (-1,-1).
    emit("\t\t{" + _log('"no army found; nothing placed"') + "}ifelse")

    emit("\tzlog closefile")
    emit("\tend")
    emit("\t}if")
    emit("}addhotkey")
    emit("; ---- END SPRITE PLACEMENT PROBE ----")
    return "\n".join(lines) + "\n"



# --- elevation probe -------------------------------------------------------------------------
#
# The ladder run settled the compositing questions and left one thing open: the measured anchor y
# is not linear in the cell (156, 167, 230, 265 across cells 60, 62, 66, 68 of a single row) while
# `map2screen`'s first two outputs are perfectly linear at 14.4 per isometric step. Terrain
# elevation is the candidate, and the probe passed `z = 0`.
#
# This probe tests that directly rather than fitting a curve to it. For a neighbourhood of cells it
# logs `getelevation` beside `map2screen` called BOTH ways -- once with z = 0, once with z set to
# that cell's elevation. If the elevation-fed call predicts the anchors we then measure from real
# placements, the z input is identified and the y convention closes.

# Offsets for the placements. Screen x moves by 33.941 * (dx - dy), so these six are distinct on
# screen, spread over both axes, and separated by more than the 72-pixel frame width.
PLACEMENT_OFFSETS: list[tuple[int, int]] = [(-6, 0), (-3, 0), (3, 0), (6, 0), (0, 3), (0, -3)]

# Half-width of the surveyed square. The survey places nothing, so it is nearly free.
SURVEY_RADIUS = 4

# One custom type built from shipped art, which the ladder run proved renders.
ELEVATION_SPRITE = '["imp/tree4e.imp"]cvx addterrainspritetype'


def elevation_body() -> str:
    lines: list[str] = []
    emit = lines.append

    emit("; ---- BEGIN ELEVATION PROBE (generated by tools/engine_probe.py) ----")
    emit(f'ASCII_VAL"{HOTKEY}"0 get')
    emit("{")
    emit("userdict /zdone known not")
    emit("\t{")
    emit("\tuserdict begin")
    emit("\t/zdone true def")
    emit('\t"zprobe.log""abw"file /zlog exch def')
    emit("\trendermap refreshdirty")
    emit('\t"ze0.bmp"screencapture')
    emit("\t/zaloc -1 def /zseen false def")
    emit(
        "\tcurrentplayer{zseen not{anythinglocation /zaloc exch def /zseen true def}"
        "{pop}ifelse}enumplayerarmies"
    )
    emit("\tzseen")
    emit("\t\t{")
    emit("\t\tzaloc xy_to_x_y /zay0 exch def /zax0 exch def")
    emit("\t\t" + _log('"army loc "zaloc" cell "zax0" "zay0'))

    # The field survey: elevation and both map2screen calls for every cell in the neighbourhood.
    # Nothing is placed, so this costs only log lines and cannot disturb the map.
    radius = SURVEY_RADIUS
    emit(f"\t\t{-radius} 1 {radius}{{/zdy exch def")
    emit(f"\t\t{-radius} 1 {radius}{{/zdx exch def")
    emit("\t\t/zcx zax0 zdx add def /zcy zay0 zdy add def")
    emit("\t\tzcx zcy getelevation /ze exch def")
    emit("\t\tzcx zcy 0 map2screen /zb3 exch def /zb2 exch def /zb1 exch def")
    emit("\t\tzcx zcy ze map2screen /zn3 exch def /zn2 exch def /zn1 exch def")
    emit(
        "\t\t"
        + _log(
            '"field "zcx" "zcy" elev "ze" z0 "zb1" "zb2" "zb3" ze "zn1" "zn2" "zn3'
        )
    )
    emit("\t\t}for")
    emit("\t\t}for")

    # The placements, which are what actually measure an anchor.
    emit(f"\t\t{ELEVATION_SPRITE} /zt exch def")
    for index, (dx, dy) in enumerate(PLACEMENT_OFFSETS):
        emit(
            f"\t\tzax0 {dx} add zay0 {dy} add x_y_to_xy UNITTYPELAND findemptylocation "
            f"/zl{index} exch def"
        )
        emit(f"\t\tzl{index} xy_to_x_y /zy{index} exch def /zx{index} exch def")
        emit(f"\t\tzx{index} zy{index} getelevation /ze{index} exch def")
        emit(f"\t\tzx{index} zy{index} 0 map2screen /zb3 exch def /zb2 exch def /zb1 exch def")
        emit(
            f"\t\tzx{index} zy{index} ze{index} map2screen "
            "/zn3 exch def /zn2 exch def /zn1 exch def"
        )
        emit(
            "\t\t"
            + _log(
                f'"place {index} loc "zl{index}" cell "zx{index}" "zy{index}'
                f'" elev "ze{index}" z0 "zb1" "zb2" "zb3" ze "zn1" "zn2" "zn3'
            )
        )
        emit(f"\t\tzx{index} zy{index} zt addterrainsprite")
    emit("\t\trendermap refreshdirty")
    emit('\t\t"ze1.bmp"screencapture')

    # `zt` was minted by this keypress, so a type-only sweep cannot touch anything of the game's.
    # The cell-qualified pass runs first anyway, for the same reason it does in the ladder.
    for index in range(len(PLACEMENT_OFFSETS)):
        emit(
            f"\t\t{{dup getterrainspritetype zt eq"
            f"{{dup getterrainspritelocation zl{index} eq"
            "{destroyterrainsprite}{pop}ifelse}"
            "{pop}ifelse}enumterrainsprites"
        )
    emit(
        "\t\t{dup getterrainspritetype zt eq"
        "{destroyterrainsprite}{pop}ifelse}enumterrainsprites"
    )
    emit("\t\trendermap refreshdirty")
    emit('\t\t"ze2.bmp"screencapture')
    emit("\t\t" + _log('"cleanup done"'))
    emit("\t\t}")
    emit("\t\t{" + _log('"no army found; nothing placed"') + "}ifelse")
    emit("\tzlog closefile")
    emit("\tend")
    emit("\t}if")
    emit("}addhotkey")
    emit("; ---- END ELEVATION PROBE ----")
    return "\n".join(lines) + "\n"

# --- oversized map probe ---------------------------------------------------------------------
#
# Issue #22 asks whether a map larger than the original maximum omits the four-byte word at 0x00,
# shifting every later offset. It was parked for want of an oversized map. It does not need one
# from outside: the shipped GS5R3 editor generates 32 to 1024 in steps of 32, and both halves of
# the operation are reachable from script.
#
# Operand orders come from shipped call sites, which is the only source allowed to settle them:
#
#     gs\edit\mapgen.gs:306   newmapdict begin map_width 32 mul map_height 32 mul end
#                              make_custom_random_map          -- width first
#     gs\rmg.gs               /map_custom_parameters{/mh exch def /mw exch def ...}
#                                                              -- pops height, then width
#     gs\hotkey.gs:562        mapfilename savescenariomap     -- one string, pushes a result
#
# This is a ladder, not a measurement. 128 is the size every shipped world map uses and 256 is the
# largest in the corpus, so both can be compared against files the game itself shipped. If a
# generated 128 does not match the shipped 128 layout, the generator is not a faithful writer and
# nothing the 512 says can be trusted -- that is the control, and it has to come first. 512 is the
# subject. Whichever rung fails names the cause.
MAP_SIZES: list[int] = [128, 256, 512]

# `savescenariomap` takes the string buffer idiom every shipped call site uses -- `/mapfilename 100
# string def`, filled by `strcpy` -- rather than a bare literal. Same type either way, but the probe
# does not get to find that out the hard way on an attended run.
MAP_NAME_BUFFER = 100


def generate_call(width: int, height: int) -> str:
    """The generator call, width first.

    Factored out so the operand order can be tested with unequal arguments. Every size in the
    ladder is square, so a test written against the ladder alone would pass just as happily with
    the operands transposed -- and this is exactly the kind of order the arity table cannot settle
    and a shipped call site had to (`gs\\edit\\mapgen.gs:306`).
    """
    return f"{width} {height} make_custom_random_map"


def map_size_map_names() -> list[str]:
    """Exactly the map files the mapsize probe writes, as `map/`-relative names."""
    return [f"map/zz{size}.scn" for size in MAP_SIZES]


def generated_map_names() -> list[str]:
    """Every map file any probe writes, as `map/`-relative names.

    The install and restore scripts clear and collect by this list rather than by a `zz*.scn`
    glob. A glob is a standing offer to delete somebody's `zzCustom.scn`, and the game's loose
    `map/` directory has no backup: the manifest covers `gs.mpq` and `imp.mpq` only. An exact
    list can only ever match files a probe created.

    It is the union across probes on purpose. Cleanup has to cover every name any probe can
    leave behind -- a previous run's leftovers are exactly what a later run must not collect as
    its own -- while each probe's own test asserts its own list, so a name cannot drift between
    the two without something failing.
    """
    return map_size_map_names() + map_tag_map_names()


def map_size_body() -> str:
    lines: list[str] = []
    emit = lines.append

    emit("; ---- BEGIN OVERSIZED MAP PROBE (generated by tools/engine_probe.py) ----")
    emit(f'ASCII_VAL"{HOTKEY}"0 get')
    emit("{")
    emit("userdict /zdone known not")
    emit("\t{")
    emit("\tuserdict begin")
    emit("\t/zdone true def")
    emit('\t"zprobe.log""abw"file /zlog exch def')
    emit(f"\t/zname {MAP_NAME_BUFFER} string def")
    emit("\t" + _log('"map size ladder start"'))

    for size, map_name in zip(MAP_SIZES, generated_map_names()):
        # The log is closed and reopened around every rung. `savescenariomap` on a 512 is the rung
        # most likely to fault or hang -- it is the one the editor itself warns about -- and an
        # unflushed buffer would take the 128 and 256 control results down with it. The ladder is
        # worth nothing if a failure on the subject erases the controls. "abw" appends.
        emit("\t" + _log(f'"gen begin "{size}'))
        # No `clearmap` here. The editor's generate branch calls `0 clearmap` first, but only to
        # blank a map it already has loaded; `make_random_map` opens with `mw mh newmap` itself
        # (gs\rmg.gs), so clearmap is redundant -- and it reads `mapw`/`maph`, which makes it a
        # precondition on there already being a map. The probe should not need one.
        emit("\t" + generate_call(size, size))
        emit("\tresetvisibility rendermap")
        # `mapw`/`maph` are the engine's own view of the live map. If the engine silently clamped
        # the request, this is where it shows, and it separates "the generator refused" from "the
        # file is written differently".
        emit("\t" + _log(f'"gen done "{size}" mapw "mapw" maph "maph'))
        emit(f'\tzname"{map_name}"strcpy')
        # All six shipped call sites read `savescenariomap pop`, so it pushes exactly one value.
        # Keeping it rather than popping it is the only way to learn that a save failed.
        emit("\tzname savescenariomap /zok exch def")
        # The filename is NOT interpolated. `zname` is a 100-byte buffer holding a 13-character
        # name; whether `writestring` emits the ~87 padding bytes or stops at the first of them,
        # the result value at the end of the line is what gets lost. It is a constant here anyway.
        emit("\t" + _log(f'"save "{size}" name {map_name} result "zok'))
        emit(f'\t"zm{size}.bmp"screencapture')
        emit("\tzlog closefile")
        emit('\t"zprobe.log""abw"file /zlog exch def')

    emit("\t" + _log('"map size ladder done"'))
    emit("\tzlog closefile")
    emit("\tend")
    emit("\t}if")
    emit("}addhotkey")
    emit("; ---- END OVERSIZED MAP PROBE ----")
    return "\n".join(lines) + "\n"


# --- flat ground probe -------------------------------------------------------------------------
#
# `map2screen` is decoded, and the drawn screen x matches its third output to under a pixel. The
# drawn y only approximately matches the second output: fitting six placements gave residuals up to
# 11 pixels, and two placements sharing an `x + y` were drawn 24 pixels apart while output 2
# differed by 5.09. No rescaling of output 2 produces that.
#
# The candidate is that the renderer interpolates height across the terrain mesh instead of
# sampling the anchor cell. That hypothesis has a counter-example in hand, because it was tested
# against a map nobody chose: the elevation run measured a shipped world map, surveyed its
# neighbourhoods afterwards, and two of its six placements fell outside the surveyed square.
#
# So this probe does not measure a map. It BUILDS one. `newmap` and `setelevation` mean the mesh is
# specified rather than reconstructed, and the same six cells are then photographed three times:
#
#   A  flat        every cell 0            -- calibrates drawn y against output 2 with no z term
#   B  plateau     a uniform block at E    -- cell elevation E, neighbourhood also E
#   C  spikes      only the six cells at E -- cell elevation E, neighbourhood 0
#
# A against B gives the z term where cell and neighbourhood agree. **B against C is the whole
# experiment**: identical `getelevation` at every placement cell, identical screen x, and the only
# difference is what surrounds them. If the drawn y moves, the renderer is reading the mesh and not
# the cell, and the size of the move measures it. If it does not, interpolation is dead and the
# missing term is something else.
#
# Three things the earlier run could not do, all free here:
#   - the neighbourhood is known before placing rather than surveyed after
#   - every placement has its own screen x, so no sprite is ever matched to a cell by which
#     assignment fits best
#   - the map is one this probe created, so nothing of the game's is at risk at any point

# Cells along one row. Screen x is `33.941 * (x - y) + L`, so a step of 3 in x puts them 101.8
# pixels apart -- wider than the donor frame -- and six of them span 509 pixels.
FLAT_ROW_Y = 32
FLAT_ROW_X = [26, 29, 32, 35, 38, 41]

# The camera is pointed with `centeron` rather than assumed; every earlier probe anchored on an army
# and inherited wherever the player had scrolled to. `x - y = 2` centres the row's *drawn content*,
# not its anchors: `map2screen`'s third output is the drawn LEFT edge, so the frame extends further
# right and a camera that centres the anchors clips the last sprite off a 640-pixel screen.
FLAT_CAMERA = (34, 32)

FLAT_MAP = 64

# The block raised for the plateau phase: every placement cell with three clear cells around it, so
# no placement's neighbourhood can see the block's edge.
FLAT_BLOCK = (23, 29, 44, 35)

# A seventh sprite on ground that is flat in ALL THREE phases, well clear of the block.
#
# It exists because the camera cannot be moved out of the plateau. The view has to frame the row,
# which fixes `cx - cy` and `cx + cy` to within a cell or two of the row itself, so the camera cell
# is inside any block that covers the placements with a margin. If `centeron` derives its offset
# from terrain height the way the sprite renderer may, the whole viewport shifts about 41 pixels
# between the plateau and spike phases, every sprite moves with it, and the uniform `392` texture
# leaves no landmark to notice it -- a camera artefact would read as the mesh coefficient, or cancel
# a real one into a false null.
#
# This sprite's own ground never changes, so any movement in ITS drawn y between phases is purely
# camera and is subtracted from the rest. It shares placement 0's screen x deliberately: the six
# columns are spoken for, and 259 pixels of vertical separation keeps its component distinct.
FLAT_CONTROL = (35, 41)

# The raised elevation. `20.3625 * 2.0` is about 41 pixels of output 2 -- far outside the 11-pixel
# residual being chased, so a null result is as readable as a positive one.
FLAT_ELEVATION = "2.0"

FLAT_SPRITE = '["imp/tree4e.imp"]cvx addterrainspritetype'

# Every probe owns its capture names. The ladder and the elevation probe both used `zp0`/`zs1`/
# `zs2`, so collecting one run overwrote the other's; the same collision on `zprobe.log` destroyed
# the elevation run's survey log on 2026-09-17. The restore script now also files each run in its
# own directory -- these prefixes are the second line of defence, and a test enforces them.
FLAT_PHASES = [
    ("flat", "zf0.bmp", "zf1.bmp"),
    ("plateau", "zf2.bmp", "zf3.bmp"),
    ("spike", "zf4.bmp", "zf5.bmp"),
]


def _flat_cells() -> list[tuple[int, int]]:
    """Every cell this probe places on: the six row cells, then the flat-ground control."""
    return [(x, FLAT_ROW_Y) for x in FLAT_ROW_X] + [FLAT_CONTROL]


def _flat_log_geometry(emit, label: str) -> None:
    """Elevation plus both `map2screen` calls for the cell in `zx`/`zy`."""
    emit("\t\tzx zy getelevation /ze exch def")
    emit("\t\tzx zy 0 map2screen /zb3 exch def /zb2 exch def /zb1 exch def")
    emit("\t\tzx zy ze map2screen /zn3 exch def /zn2 exch def /zn1 exch def")
    emit(
        "\t\t"
        + _log(
            f'"{label} cell "zx" "zy" elev "ze'
            '" z0 "zb1" "zb2" "zb3" ze "zn1" "zn2" "zn3'
        )
    )


def _flat_survey(emit, tag: str) -> None:
    """Log every placement cell and its eight neighbours, so the mesh is recorded, not assumed.

    `setelevation` may or may not be clamped against `maxslope`; a spike beside flat ground is a
    steep slope. If the engine smooths it, the plateau and spike phases differ in the CELL's
    elevation too and the experiment is void -- this survey is what makes that visible in the log
    rather than silently wrong.
    """
    emit("\t\t-1 1 1{/zdy exch def")
    emit("\t\t-1 1 1{/zdx exch def")
    emit(f"\t\t0 1 {len(FLAT_ROW_X) - 1}{{/zi exch def")
    emit(f"\t\t/zx zrow zi get zdx add def /zy {FLAT_ROW_Y} zdy add def")
    emit("\t\tzx zy getelevation /ze exch def")
    emit("\t\t" + _log(f'"field {tag} "zi" "zdx" "zdy" cell "zx" "zy" elev "ze'))
    emit("\t\t}for")
    emit("\t\t}for")
    emit("\t\t}for")


def _flat_set_block(emit, x0: int, y0: int, x1: int, y1: int, value: str) -> None:
    """`x y elevation setelevation`, from `tempx tempy rad_val setelevation` in the editor."""
    emit(f"\t\t{x0} 1 {x1}{{/zsx exch def")
    emit(f"\t\t{y0} 1 {y1}{{/zsy exch def")
    emit(f"\t\tzsx zsy {value} setelevation")
    emit("\t\t}for")
    emit("\t\t}for")


def _flat_phase(emit, tag: str, plate: str, shot: str) -> None:
    """Rebuild, re-point, plate, place, photograph, then sweep and COUNT what survived."""
    # The mesh has to be rebuilt after elevations change or the render keeps the old heights, and
    # the camera is re-pointed because a rebuild is not guaranteed to preserve it.
    emit("\t\trebuild3dmap resetvisibility rendermap refreshdirty")
    emit(f"\t\t{FLAT_CAMERA[0]} {FLAT_CAMERA[1]} centeron")
    emit("\t\trendermap refreshdirty")
    _flat_survey(emit, tag)
    # The plate is taken after the elevation change and BEFORE any placement: each phase is
    # differenced against its own terrain, and a plate containing the sprites reads as "nothing
    # rendered".
    emit(f'\t\t"{plate}"screencapture')
    for index, (cell_x, cell_y) in enumerate(_flat_cells()):
        label = f"place {tag} {index}"
        if (cell_x, cell_y) == FLAT_CONTROL:
            label = f"control {tag}"
        emit(f"\t\t/zx {cell_x} def /zy {cell_y} def")
        _flat_log_geometry(emit, label)
        emit("\t\tzx zy zt addterrainsprite")
    emit("\t\trendermap refreshdirty")
    emit(f'\t\t"{shot}"screencapture')
    # Two sweeps, as the ladder and elevation probes do: destroying during an enumeration may
    # advance past an entry, and a survivor left standing is the same art on the same cell in the
    # next phase's plate AND shot -- it contributes zero changed pixels and reads exactly like
    # "the sprite did not render".
    #
    # `zt` was minted by this keypress and the map is this probe's own creation, so a type-only
    # sweep cannot touch anything else.
    for _ in range(2):
        emit(
            "\t\t{dup getterrainspritetype zt eq"
            "{destroyterrainsprite}{pop}ifelse}enumterrainsprites"
        )
    # And then count, because a silent skip is exactly what the two sweeps are guarding against.
    # A non-zero count here names the failure in the log instead of corrupting the next phase.
    emit("\t\t/zleft 0 def")
    emit(
        "\t\t{dup getterrainspritetype zt eq{/zleft zleft 1 add def}if pop}enumterrainsprites"
    )
    emit("\t\trendermap refreshdirty")
    emit("\t\t" + _log(f'"cleanup {tag} left "zleft'))


def flat_ground_body() -> str:
    lines: list[str] = []
    emit = lines.append
    x0, y0, x1, y1 = FLAT_BLOCK

    emit("; ---- BEGIN FLAT GROUND PROBE (generated by tools/engine_probe.py) ----")
    emit(f'ASCII_VAL"{HOTKEY}"0 get')
    emit("{")
    emit("userdict /zdone known not")
    emit("\t{")
    emit("\tuserdict begin")
    emit("\t/zdone true def")
    emit('\t"zprobe.log""abw"file /zlog exch def')
    emit("\t" + _log('"flat ground probe start"'))
    emit("\t/zrow[" + " ".join(str(value) for value in FLAT_ROW_X) + "]def")
    # Build the map. `392 clearmap` is the texture the shipped `generate_simple_game` uses, and
    # clearmap re-runs `mapw maph newmap` before painting it over every cell.
    emit(
        f"\t{{}}gamemodeproc gamemode {FLAT_MAP} {FLAT_MAP} newmap 392 clearmap default_edit_mode"
    )
    emit("\t" + _log(f'"map built "mapw" "maph'))
    emit(f"\t{FLAT_SPRITE} /zt exch def")
    emit("\t" + _log('"sprite type "zt'))

    # Phase A: everything flat. Explicit rather than trusting newmap to zero the mesh -- the whole
    # experiment rests on knowing the elevations, so they are set, not assumed.
    _flat_set_block(emit, 0, 0, FLAT_MAP - 1, FLAT_MAP - 1, "0")
    _flat_phase(emit, *FLAT_PHASES[0])

    # Phase B: a uniform raised block. Cell and neighbourhood agree.
    _flat_set_block(emit, x0, y0, x1, y1, FLAT_ELEVATION)
    _flat_phase(emit, *FLAT_PHASES[1])

    # Phase C: the block goes back down and only the six placement cells stay raised. Same
    # `getelevation` at every placement cell as phase B, opposite neighbourhood.
    _flat_set_block(emit, x0, y0, x1, y1, "0")
    for index in range(len(FLAT_ROW_X)):
        emit(f"\t\tzrow {index} get {FLAT_ROW_Y} {FLAT_ELEVATION} setelevation")
    _flat_phase(emit, *FLAT_PHASES[2])

    emit("\t" + _log('"flat ground probe done"'))
    emit("\tzlog closefile")
    emit("\tend")
    emit("\t}if")
    emit("}addhotkey")
    emit("; ---- END FLAT GROUND PROBE ----")
    return "\n".join(lines) + "\n"


# --- map cell tag probe ------------------------------------------------------------------------
#
# Issue #4. The 8-byte map cell is half decoded: the second word is a finite float that renders as
# coherent world relief, and the first word is opaque. Masking `0x00800000` out of all 1,258,496
# corpus cells leaves 603 distinct values in `0..623`, exactly the slot range of the 624-tile
# atlas `tilesb01.til` declares, and rendering through those indices produces a correctly oriented
# world. So "the low bits are a tile index" is already strong. What is *not* established is what
# the `0x00800000` flag means, where the terrain TYPE lives, and why the shipped corpus only ever
# sets that flag in `.smp` files.
#
# The editor has two separate paints, and that is the whole experiment:
#
#   setterrain   x y terrain    gs\rmg.gs        terrain type 0..10, engine picks the tile
#   forcetexture x y texture    gs\maplib.gs     tile slot directly, engine picks nothing
#
# `forcetexture` arity was recovered from its four shipped call sites, not from the arity table.
# `/clearmap{/temp_tex exch def mapw maph newmap 0 1 maph 1 sub{/y exch def 0 1 mapw 1 sub{y
# temp_tex forcetexture}for}for}def` puts x on the stack from the inner `for`, so the order is
# `x y texture`; `show_regions`'s `x y 2 copy regionatlocation 48 mul forcetexture` and
# `mountain`'s `mtn_y add tempx exch 48 forcetexture` both agree.
#
# The prediction is therefore sharp enough to be wrong:
#
#   a forced cell   tag low bits == the exact slot we asked for, and `0x00800000` SET
#   a terrained cell  `0x00800000` CLEAR, low bits == whatever tile the engine chose
#
# If the flag is set on both rows, or neither, "forced texture" is refuted and the flag is
# something else. Nothing about this is inferred from the corpus: every cell is written to a value
# this probe chose, so the file can be read back by construction rather than by correlation.
#
# `getterrain` is logged for the forced row as well, and that is the second result. `.til` declares
# tile-to-terrain relationships, so if the engine reports a terrain type for a cell whose type was
# never set, the type is derived from the tile index -- which is the only way the 8-byte cell can
# hold both, since bits 10..22 of the tag are unused across the whole corpus. That also recovers
# the engine's own tile-to-terrain table, which can be checked against our `.til` parse.
MAPTAG_MAP = 64

# `392` is the texture `gs\edit\generate.gs`'s `generate_simple_game` clears with, so the
# background is a value the shipped scripts themselves use.
MAPTAG_BASE_TEXTURE = 392

# Slots spread across the atlas. `0`, `48` and `392` appear in shipped call sites; `623` is the
# last slot `tilesb01.til` declares and the largest index observed in the corpus, so it is in range
# but is the one most likely to fault. Each cell is logged after it is painted, so if the body dies
# the last line in the log names the last slot the engine accepted.
MAPTAG_TEXTURE_ROW = 8
MAPTAG_TEXTURES = [0, 1, 2, 48, 96, 392, 623]

# Every terrain type `gs\maplib.gs` defines, 0..10, in order. Two rows keeps the readback
# unambiguous: a cell is painted by exactly one of the two operators, never both.
MAPTAG_TERRAIN_ROW = 12
MAPTAG_TERRAINS = list(range(11))

# Cells are spaced two apart so a mistake in the x stride shows as a gap rather than as a
# plausible-looking shift.
MAPTAG_FIRST_X = 8
MAPTAG_X_STRIDE = 2

# Three cells, deliberately NOT collinear and NOT symmetric: (18,14) and (19,14) differ only in x,
# (18,14) and (18,15) only in y. Packed `y*width+x` gives 914/915/978 and X-major `x*height+y` gives
# 1166/1230/1167, so whichever the record holds, the three values identify the order. That is what
# the 2026-09-17 run settled -- the records carried the packed values -- and keeping the asymmetry
# means a future change to the parser still has to face a fixture that can tell them apart.
#
# They sit beside the camera because the first run's did not. Those were (20,30), (21,30), (20,31),
# which the projection puts ~339 pixels left of centre and ~259 below it: off the left edge and
# under the editor's panel. The sprites were placed -- the log counted them and the saved records
# were right -- but the plate and the shot came back differing by zero bytes, so the capture pair
# cost a screenshot each and proved nothing. `map_projection.is_in_frame` now decides this instead
# of hope, and a test holds every placement cell to it.
MAPTAG_SPRITE_CELLS = [(18, 14), (19, 14), (18, 15)]
MAPTAG_SPRITE = '["imp/tree4e.imp"]cvx addterrainspritetype'

# Camera. The painted rows at y 8 and 12 run off the frame at their far ends, so the capture never
# shows all of both -- the saved bytes carry the terrain result. The sprites are a different matter:
# they are placed beside the camera so they ARE in frame, and `map_projection.is_in_frame` holds
# them to it. A capture pair around a placement nobody can see is two screenshots and no evidence.
MAPTAG_CAMERA = (16, 16)

# Own capture prefix, like every other probe. `zl*` ladder, `ze*` elevation, `zm*` mapsize,
# `zf*` flatground, `zg*` here.
MAPTAG_PLATE = "zg0.bmp"
MAPTAG_SHOT = "zg1.bmp"


def map_tag_map_names() -> list[str]:
    """The four files this probe saves, in the order it writes them.

    `zzt0.scn` and `zzt0.smp` are the same map state saved twice, and that pairing is the point:
    the corpus's 52-byte trailing records occur almost entirely in `.smp` files and the 49-byte
    ones almost entirely in `.scn`, which is either a format difference or a content difference
    and cannot be told apart from shipped files alone. Saving one state both ways separates them.

    `zzt1.scn` adds three sprites to that same state and `zzt2.scn` removes them again, so the
    trailing bytes a placed sprite costs can be read off a diff instead of being pattern-matched.
    """
    return ["map/zzt0.scn", "map/zzt0.smp", "map/zzt1.scn", "map/zzt2.scn"]


def _map_tag_cells(values: list[int], row: int) -> list[tuple[int, int, int]]:
    """`(x, y, value)` for one painted row."""
    return [
        (MAPTAG_FIRST_X + index * MAPTAG_X_STRIDE, row, value)
        for index, value in enumerate(values)
    ]


def _map_tag_count(emit, tag: str) -> None:
    """Log how many sprites of the probe's own type are on the map right now."""
    emit("\t/zn 0 def")
    emit("\t{dup getterrainspritetype zt eq{/zn zn 1 add def}if pop}enumterrainsprites")
    emit("\t" + _log(f'"count {tag} "zn'))


def _map_tag_save(emit, operator: str, map_name: str, tag: str) -> None:
    """Save, keep the result, log it, then cycle the log file.

    All six shipped call sites of both `savescenariomap` and `savespecialmap` read
    `... savescenariomap pop`, so each pushes exactly one value; keeping it is the only way to
    learn that a save failed. The log is closed and reopened after every save for the same reason
    the mapsize ladder does it -- a fault on a later write must not take the earlier results down
    with it.
    """
    emit(f'\tzname"{map_name}"strcpy')
    emit(f"\tzname {operator} /zok exch def")
    # The filename is not interpolated: `zname` is a 100-byte buffer holding a short name, and
    # whether `writestring` stops at the first padding byte or emits all of them, it is the result
    # at the end of the line that would be lost. It is a constant here anyway.
    emit("\t" + _log(f'"save {tag} {map_name} result "zok'))
    emit("\tzlog closefile")
    emit('\t"zprobe.log""abw"file /zlog exch def')


def map_tag_body() -> str:
    lines: list[str] = []
    emit = lines.append

    emit("; ---- BEGIN MAP CELL TAG PROBE (generated by tools/engine_probe.py) ----")
    emit(f'ASCII_VAL"{HOTKEY}"0 get')
    emit("{")
    emit("userdict /zdone known not")
    emit("\t{")
    emit("\tuserdict begin")
    emit("\t/zdone true def")
    emit('\t"zprobe.log""abw"file /zlog exch def')
    emit(f"\t/zname {MAP_NAME_BUFFER} string def")
    emit("\t" + _log('"map cell tag probe start"'))

    # Build the map. `clearmap` re-runs `mapw maph newmap` itself and then forcetextures every
    # cell, so the background is a known slot AND, if the flag means what we think, every cell
    # starts flagged. The two painted rows then have to clear it or set it differently.
    emit(f"\t{MAPTAG_MAP} {MAPTAG_MAP} newmap {MAPTAG_BASE_TEXTURE} clearmap")
    emit("\t" + _log(f'"map built "mapw" "maph" base {MAPTAG_BASE_TEXTURE}"'))

    for cell_x, cell_y, texture in _map_tag_cells(MAPTAG_TEXTURES, MAPTAG_TEXTURE_ROW):
        emit(f"\t/zx {cell_x} def /zy {cell_y} def")
        emit(f"\tzx zy {texture} forcetexture")
        # Read the terrain type back from a cell whose type was never set. If the engine reports
        # one, it came from the tile index via the `.til` relationships -- and this line is the
        # engine's own tile-to-terrain table, recovered without parsing the tileset.
        emit("\tzx zy getterrain /zg exch def")
        emit("\t" + _log(f'"forced cell "zx" "zy" texture {texture} terrain "zg'))

    for cell_x, cell_y, terrain in _map_tag_cells(MAPTAG_TERRAINS, MAPTAG_TERRAIN_ROW):
        emit(f"\t/zx {cell_x} def /zy {cell_y} def")
        emit(f"\tzx zy {terrain} setterrain")
        emit("\tzx zy getterrain /zg exch def")
        emit("\t" + _log(f'"terrain cell "zx" "zy" set {terrain} terrain "zg'))

    emit("\trebuild3dmap resetvisibility rendermap refreshdirty")
    emit(f"\t{MAPTAG_CAMERA[0]} {MAPTAG_CAMERA[1]} centeron")
    emit("\trendermap refreshdirty")
    emit(f'\t"{MAPTAG_PLATE}"screencapture')

    map_names = map_tag_map_names()
    _map_tag_save(emit, "savescenariomap", map_names[0], "terrain-only scn")
    _map_tag_save(emit, "savespecialmap", map_names[1], "terrain-only smp")

    emit(f"\t{MAPTAG_SPRITE} /zt exch def")
    emit("\t" + _log('"sprite type "zt'))
    _map_tag_count(emit, "before")
    for index, (cell_x, cell_y) in enumerate(MAPTAG_SPRITE_CELLS):
        emit(f"\t/zx {cell_x} def /zy {cell_y} def")
        emit("\tzx zy zt addterrainsprite")
        _map_tag_count(emit, f"after {index} cell {cell_x} {cell_y}")
    emit("\trendermap refreshdirty")
    emit(f'\t"{MAPTAG_SHOT}"screencapture')
    _map_tag_save(emit, "savescenariomap", map_names[2], "with sprites")

    # Two sweeps. Destroying during an enumeration may advance past an entry, and a survivor
    # would land in the "removed" save and make the diff read as "the record was never written".
    # `zt` was minted by this keypress and the map is this probe's own creation, so a type-only
    # sweep cannot reach anything the probe did not place.
    for _ in range(2):
        emit(
            "\t{dup getterrainspritetype zt eq"
            "{destroyterrainsprite}{pop}ifelse}enumterrainsprites"
        )
    _map_tag_count(emit, "after cleanup")
    emit("\trendermap refreshdirty")
    _map_tag_save(emit, "savescenariomap", map_names[3], "sprites removed")

    emit("\t" + _log('"map cell tag probe done"'))
    emit("\tzlog closefile")
    emit("\tend")
    emit("\t}if")
    emit("}addhotkey")
    emit("; ---- END MAP CELL TAG PROBE ----")
    return "\n".join(lines) + "\n"


PROBES = {
    "ladder": lambda: probe_body(),
    "elevation": elevation_body,
    "mapsize": map_size_body,
    "flatground": flat_ground_body,
    "maptag": map_tag_body,
}


def install(hotkey_source: str, probe: str = "ladder") -> str:
    """Insert a probe before `hotkey.gs`'s final `end`, which the file warns not to pass."""
    if probe not in PROBES:
        raise ValueError(f"unknown probe {probe!r}; choose from {sorted(PROBES)}")
    marker = "\nend ; DO NOT ADD AFTER 'END'!"
    if hotkey_source.count(marker) != 1:
        raise ValueError(
            f"expected exactly one {marker.strip()!r} marker, found "
            f"{hotkey_source.count(marker)}"
        )
    return hotkey_source.replace(marker, "\n" + PROBES[probe]() + marker)


def disable_intro(start_source: str) -> str:
    """Turn off the two startup movies, which cost minutes of every attended run."""
    guard = '\ntrue\n\t{\n\t75 75"smk/imptitle.smk"MODAL playvideo '
    if start_source.count(guard) != 1:
        raise ValueError("START.GS intro guard not found in its expected form")
    return start_source.replace(guard, guard.replace("\ntrue\n", "\nfalse\n", 1), 1)


